// Copies static/llms-full.txt into the job-fit function so the model reasons from exactly what the site publishes.
// Run after editing llms-full.txt:  node scripts/sync-fit-profile.mjs
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync(new URL("../static/llms-full.txt", import.meta.url), "utf8").trim();
const esc = src.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
writeFileSync(
  new URL("../supabase/functions/job-fit/profile.ts", import.meta.url),
  `// GENERATED by scripts/sync-fit-profile.mjs from static/llms-full.txt. Do not edit by hand.\nexport const PROFILE = \`${esc}\`;\n`
);
console.log("profile.ts written,", src.length, "chars");
